const fs=require('node:fs');
const rows=fs.readFileSync('dist/locales.tsv','utf8').trim().split(/\r?\n/).map(line=>line.split('\t'));
for(const row of rows)if(row.length!==5)throw Error('Expected five languages: '+row[0]);
const source='/* Generated by build-i18n.cjs. */\nconst ROWS='+JSON.stringify(rows)+';\n'+fs.readFileSync('i18n-runtime.js','utf8');
for(const dir of ['dist','docs'])fs.writeFileSync(dir+'/i18n.js',source);
console.log('Built '+rows.length+' translations in five languages.');
